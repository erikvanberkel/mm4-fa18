// Builds dist/: bundles the AudioWorklet to a string, bundles the game, writes index.html and a
// single-file copy. `node tools/build.mjs --watch` rebuilds on change (used by the dev server).
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import esbuild from 'esbuild';

const ROOT = new URL('../', import.meta.url);
const p = (rel) => fileURLToPath(new URL(rel, ROOT));
const watch = process.argv.includes('--watch');
const dev = watch || process.argv.includes('--dev');

export async function buildWorklet() {
  const r = await esbuild.build({
    entryPoints: [p('src/audio/worklet-entry.js')],
    bundle: true, format: 'iife', write: false, minify: !dev, target: 'es2020', logLevel: 'warning',
  });
  const text = r.outputFiles[0].text;
  fs.writeFileSync(p('src/audio/worklet.gen.js'), `// GENERATED by tools/build.mjs. Do not edit.\nexport default ${JSON.stringify(text)};\n`);
  return text.length;
}

export async function build({ watchMode = watch } = {}) {
  fs.mkdirSync(p('dist'), { recursive: true });
  const wl = await buildWorklet();
  const opts = {
    entryPoints: [p('src/main.js')],
    bundle: true, format: 'iife', outfile: p('dist/game.js'),
    minify: !dev, sourcemap: dev, target: 'es2020', logLevel: 'info', legalComments: 'none',
  };
  fs.copyFileSync(p('index.html'), p('dist/index.html'));
  if (watchMode) {
    const ctx = await esbuild.context(opts);
    await ctx.watch();
    return ctx;
  }
  await esbuild.build(opts);
  // Single-file build: everything inline, playable straight from disk.
  const js = fs.readFileSync(p('dist/game.js'), 'utf8').replace(/<\/script/g, '<\\/script');
  const html = fs.readFileSync(p('index.html'), 'utf8').replace('<script src="game.js"></script>', () => `<script>${js}</script>`);
  fs.writeFileSync(p('dist/fa18-interceptor.html'), html);
  console.log(`worklet ${wl} B, game.js ${(fs.statSync(p('dist/game.js')).size / 1024) | 0} KB, single file ${(fs.statSync(p('dist/fa18-interceptor.html')).size / 1024) | 0} KB`);
  return null;
}

if (process.argv[1] && process.argv[1].endsWith('build.mjs')) {
  const ctx = await build();
  if (watch) console.log('watching...');
  void ctx;
}
