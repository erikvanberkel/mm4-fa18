// Two hand-made bitmap fonts: a 4x6 for the HUD and panel, and a 7x8 stencil-cut menu face
// in the spirit of the original's squared-off, broken-stroke lettering.

function parse(table, width) {
  const glyphs = {};
  for (const [chars, rows] of table) {
    glyphs[chars] = rows.map((r) => {
      let bits = 0;
      for (let i = 0; i < width; i++) if (r[i] === '#') bits |= 1 << i;
      return bits;
    });
  }
  return glyphs;
}

